func TestStructTemplate_ExecuteMinimal(t *testing.T) {
	data := templateData{
		Pkg:          "mypkg",
		TypePkg:      "",
		Name:         "User",
		FieldAlias:   "fld",
		MongoAlias:   "mg",
		FilterAlias:  "flt",
		UpdaterAlias: "upd",
		Imports:      nil,
		Fields:       nil,
		Inlines:      nil,
		EqualAble:    false,
	}

	var buf bytes.Buffer
	if err := structTemplate.Execute(&buf, data); err != nil {
		t.Fatalf("Execute error: %v", err)
	}

	out := buf.String()
	checks := []string{
		"Code generated by go-mongodb-gen",
		"package mypkg",
		"type LikeUserField[T any] interface",
		"type UserField = LikeUserField[User]",
		"type likeUserField[T any] struct",
		"func NewLikeUserField[T any](name string) LikeUserField[T]",
		"var UserDoc = NewUserField(\"\")",
		"var NewUserField = NewLikeUserField[User]",
	}
	for _, c := range checks {
		if !strings.Contains(out, c) {
			t.Errorf("output missing %q\n---output---\n%s", c, out)
		}
	}
}

func TestStructTemplate_EqualAbleTrue(t *testing.T) {
	data := templateData{
		Pkg:          "mypkg",
		Name:         "User",
		FieldAlias:   "fld",
		MongoAlias:   "mg",
		FilterAlias:  "flt",
		UpdaterAlias: "upd",
		EqualAble:    true,
	}

	var buf bytes.Buffer
	if err := structTemplate.Execute(&buf, data); err != nil {
		t.Fatalf("Execute error: %v", err)
	}

	out := buf.String()
	if !strings.Contains(out, "ComparableFilter[T]") {
		t.Error("EqualAble=true should generate ComparableFilter[T]")
	}
	if strings.Contains(out, "BaseFilter[T]") {
		t.Error("EqualAble=true should NOT generate BaseFilter[T]")
	}
}

