// ─── firstToLower ──────────────────────────────────────────

func TestFirstToLower_Basic(t *testing.T) {
	tests := []struct {
		in   string
		want string
	}{
		{"Hello", "hello"},
		{"URL", "uRL"},
		{"A", "a"},
		{"", ""},
		{"already", "already"},
		{"GoMongoDB", "goMongoDB"},
	}
	for _, tt := range tests {
		got := firstToLower(tt.in)
		if got != tt.want {
			t.Errorf("firstToLower(%q) = %q, want %q", tt.in, got, tt.want)
		}
	}
}

